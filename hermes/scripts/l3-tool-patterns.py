#!/usr/bin/env python3
"""
L3-C: 工具模式挖掘
检测 skill 中频繁手写的重复 bash/API 调用序列,
自动建议 MCP server 或脚本封装。

输出: MCP 提案, 写入 mcp/proposals/

用法:
  python3 ~/.hermes/scripts/l3-tool-patterns.py

  # 分析特定 skill
  python3 ~/.hermes/scripts/l3-tool-patterns.py --skill router

  # 设置重复阈值 (超过 N 次视为可封装)
  python3 ~/.hermes/scripts/l3-tool-patterns.py --threshold 10
"""

import os, sys, json, datetime, re
from collections import Counter, defaultdict

SKILLS_DIR = os.path.expanduser("~/.hermes/skills")
MCP_PROPOSALS = os.path.expanduser("~/.hermes/mcp/proposals")
os.makedirs(MCP_PROPOSALS, exist_ok=True)


# ─── 常见重复模式检测 ───

BASH_PATTERNS = [
    # git 操作 (应封装为 git helper)
    {"pattern": r"git\s+(add|commit|push|pull|fetch|merge|rebase|checkout|branch|log|status)",
     "name": "git_operations", "suggestion": "MCP git 工具或 git helper 脚本"},

    # npm/pnpm/yarn 操作
    {"pattern": r"(npm|pnpm|yarn)\s+(install|add|remove|run|build|test|lint)",
     "name": "package_manager", "suggestion": "MCP package-manager 工具"},

    # docker 操作
    {"pattern": r"docker\s+(build|run|pull|push|ps|logs|exec|compose|images|rm)",
     "name": "docker_operations", "suggestion": "MCP docker 工具"},

    # curl 操作
    {"pattern": r"curl\s+(-[a-zA-Z]+\s+)?['\"]?https?://",
     "name": "http_requests", "suggestion": "MCP http-client 工具"},

    # pip install
    {"pattern": r"pip\s+(install|uninstall|list|freeze)",
     "name": "python_packages", "suggestion": "MCP python-packages 工具"},

    # sed 编辑
    {"pattern": r"sed\s+-i",
     "name": "file_editing", "suggestion": "已有 patch 工具, 考虑扩展"},

    # grep/rg 搜索
    {"pattern": r"(grep|rg|ag)\s+",
     "name": "file_searching", "suggestion": "已有 search_files 工具, 无需封装"},

    # chmod/chown
    {"pattern": r"chmod|chown",
     "name": "file_permissions", "suggestion": "shell 一层即可, 无需 MCP"},

    # 数据库查询
    {"pattern": r"(psql|mysql|sqlite3|mongo)\s+",
     "name": "database_queries", "suggestion": "MCP database 工具"},

    # 文件操作 (cp, mv, rm)
    {"pattern": r"\b(cp|mv|rm)\s+-[a-zA-Z]",
     "name": "file_operations", "suggestion": "已有 filesystem MCP, 无需封装"},

    # 压缩解压
    {"pattern": r"(tar|gzip|zip|unzip)\s+",
     "name": "archive_operations", "suggestion": "shell 一层即可, 无需 MCP"},
]


def scan_skill_md(skill_dir, skill_name):
    """扫描 SKILL.md 中的 bash 代码块"""
    md_path = os.path.join(skill_dir, "SKILL.md")
    if not os.path.exists(md_path):
        return [], []

    with open(md_path) as f:
        content = f.read()

    # 提取 bash 代码块
    bash_blocks = re.findall(r'```(?:bash|sh|shell)\n(.*?)```', content, re.DOTALL)

    # 提取命令序列
    commands = []
    for block in bash_blocks:
        for line in block.strip().split("\n"):
            line = line.strip()
            if line and not line.startswith("#") and not line.startswith("//"):
                commands.append(line)

    # 匹配已知模式
    matches = Counter()
    for cmd in commands:
        for pat in BASH_PATTERNS:
            if re.search(pat["pattern"], cmd, re.IGNORECASE):
                matches[pat["name"]] += 1
                pat["found_in"] = skill_name
                break

    return commands, matches


def scan_all_skills():
    """扫描所有 skill 的 bash 模式"""
    pattern_counts = defaultdict(int)
    skill_patterns = defaultdict(lambda: defaultdict(list))

    for root, dirs, files in os.walk(SKILLS_DIR):
        if "SKILL.md" in files:
            skill_name = os.path.basename(root)
            commands, matches = scan_skill_md(root, skill_name)
            for pattern_name, count in matches.items():
                pattern_counts[pattern_name] += count
                skill_patterns[pattern_name][skill_name].append(count)

    return pattern_counts, skill_patterns


def write_mcp_proposal(pattern_name, count, skills_using, threshold=10):
    """写入 MCP server 提案"""
    if count < threshold:
        return 0

    slug = pattern_name.replace("_", "-")
    filename = f"mcp-proposal-{slug}-{datetime.datetime.now().strftime('%Y%m%d')}.md"
    filepath = os.path.join(MCP_PROPOSALS, filename)

    skills_list = "\n".join(f"  - {s}: {c[0]} times" for s, c in skills_using.items())

    content = f"""# MCP Server Proposal: {pattern_name}

Detected: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}
Total occurrences: {count}

## Observed Pattern

{pattern_name} appears {count} times across {len(skills_using)} skills.
Suggestion: {next((p['suggestion'] for p in BASH_PATTERNS if p['name'] == pattern_name), 'Consider MCP encapsulation')}

## Skills Affected

{skills_list}

## Proposed Action

(Human review required — MCP servers have filesystem/network access)

- [ ] Review the repeated pattern in affected skills
- [ ] Decide if MCP encapsulation is worth the complexity
- [ ] Implement MCP server
- [ ] Update skills to use the new MCP tool

## Auto-generated by L3-C Tool Pattern Miner
"""
    with open(filepath, "w") as f:
        f.write(content)
    return 1


def main():
    import argparse
    parser = argparse.ArgumentParser(description="L3-C: 工具模式挖掘")
    parser.add_argument("--threshold", type=int, default=10,
                        help="重复次数阈值 (默认 10)")
    parser.add_argument("--skill", default="", help="只分析特定 skill")
    args = parser.parse_args()

    if args.skill:
        # 只分析单个 skill
        skill_dir = os.path.join(SKILLS_DIR, args.skill)
        if not os.path.exists(skill_dir):
            # 搜索子目录
            for root, dirs, files in os.walk(SKILLS_DIR):
                if os.path.basename(root) == args.skill:
                    skill_dir = root
                    break
        if not os.path.exists(skill_dir):
            print(f"Skill not found: {args.skill}")
            return

        commands, matches = scan_skill_md(skill_dir, args.skill)
        print(f"\nTool pattern analysis: {args.skill}")
        print(f"  Bash commands found: {len(commands)}")
        print(f"  Patterns detected: {len(matches)}")
        for pat, count in matches.most_common():
            sugg = next((p["suggestion"] for p in BASH_PATTERNS if p["name"] == pat), "")
            print(f"    {pat}: {count}x — {sugg}")
    else:
        # 全量扫描
        print("Scanning all skills for tool patterns...")
        pattern_counts, skill_patterns = scan_all_skills()

        print(f"\nPatterns across all skills:")
        proposals = 0
        for pat, count in sorted(pattern_counts.items(), key=lambda x: -x[1]):
            skills_using = skill_patterns[pat]
            n_skills = len(skills_using)
            flag = " ⚠️  MCP CANDIDATE" if count >= args.threshold else ""
            pat_sug = next((p["suggestion"] for p in BASH_PATTERNS if p["name"] == pat), "")
            print(f"  {pat:25s}: {count:3d}x across {n_skills:2d} skills{flag}")
            if count >= args.threshold:
                print(f"    Suggestion: {pat_sug}")
                proposals += write_mcp_proposal(pat, count, skills_using, args.threshold)

        print(f"\n  MCP proposals generated: {proposals}")
        print(f"  Proposals saved to: {MCP_PROPOSALS}/")
        print("  ⚠️  All MCP proposals require human review before installation.")

    print()


if __name__ == "__main__":
    main()
